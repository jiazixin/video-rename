import {test,expect,type Page} from '@playwright/test'
async function login(page:Page){await page.goto('/');await page.getByLabel('用户名',{exact:true}).fill('admin');await page.getByLabel('密码',{exact:true}).fill('test-password-123');await page.getByRole('button',{name:'登录',exact:true}).click()}
test('固定提示词与提示词库的新增、编辑、引用保护和持久化',async({page})=>{
 await login(page)
 const fixed=page.getByLabel('固定提示词',{exact:true})
 let original=''
 try{
  await page.goto('/#settings/prompts')
  await expect(page.getByRole('heading',{name:'固定提示词',exact:true})).toBeVisible()
  original=await fixed.inputValue()
  await expect(fixed).toHaveValue(/标题正文不少于25个中文字符/)
  await expect(page.getByRole('heading',{name:'默认提示词',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'新增提示词',exact:true}).click()
  await page.getByLabel('提示词名称',{exact:true}).fill('下拉绑定提示词')
  await page.getByLabel('提示词内容',{exact:true}).fill('用于下拉绑定的提示词正文。')
  await page.getByRole('button',{name:'保存提示词',exact:true}).click()
  await expect(page.getByRole('heading',{name:'下拉绑定提示词',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'模型配置',exact:true}).click()
  await page.getByRole('button',{name:'新增配置',exact:true}).click()
  await page.getByLabel('配置名称',{exact:true}).fill('下拉测试配置')
  await page.getByLabel('服务 URL',{exact:true}).fill('http://127.0.0.1:9/v1')
  await page.getByLabel('模型名称',{exact:true}).fill('dropdown-model')
  await page.getByRole('combobox',{name:'命名提示词',exact:true}).click()
  await page.getByRole('option',{name:'下拉绑定提示词',exact:true}).click()
  await page.getByRole('button',{name:'保存配置',exact:true}).click()
  const card=page.locator('.model-card').filter({hasText:'下拉测试配置'})
  await expect(card).toContainText('命名提示词 · 下拉绑定提示词')
  await page.goto('/#settings/prompts')
  await page.getByRole('button',{name:'删除提示词 下拉绑定提示词',exact:true}).click()
  await page.getByRole('button',{name:'确认删除',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('1 个模型配置使用此提示词')
  await page.getByRole('button',{name:'取消',exact:true}).click()
  await page.getByRole('button',{name:'模型配置',exact:true}).click()
  await page.getByRole('button',{name:'编辑模型配置 下拉测试配置',exact:true}).click()
  await page.getByRole('combobox',{name:'命名提示词',exact:true}).click()
  await page.getByRole('option',{name:'默认提示词',exact:true}).click()
  await page.getByRole('button',{name:'保存配置',exact:true}).click()
  await expect(page.locator('.model-card').filter({hasText:'下拉测试配置'})).toContainText('命名提示词 · 默认提示词')
  await page.getByRole('button',{name:'删除模型配置 下拉测试配置',exact:true}).click()
  await page.getByRole('button',{name:'确认删除',exact:true}).click()
  await expect(page.locator('.model-card').filter({hasText:'下拉测试配置'})).toHaveCount(0)
  await page.goto('/#settings/prompts')
  await page.getByRole('button',{name:'删除提示词 下拉绑定提示词',exact:true}).click()
  await page.getByRole('button',{name:'确认删除',exact:true}).click()
  await expect(page.getByRole('heading',{name:'下拉绑定提示词',exact:true})).toHaveCount(0)
  await fixed.fill('测试固定约束：只输出一行。')
  await page.getByRole('button',{name:'保存固定提示词',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('固定提示词已保存')
  await page.reload()
  await expect(fixed).toHaveValue('测试固定约束：只输出一行。')
  await page.getByRole('button',{name:'恢复默认',exact:true}).click()
  await expect(fixed).toHaveValue('输出要求：\n标题正文不少于25个中文字符，建议控制在30至50个中文字符\n最终响应只能包含一个完整的中文标题正文。\n必须单行输出。\n除标题正文之外不输出任何其他内容。')
  await expect(page.getByRole('button',{name:'保存固定提示词',exact:true})).toBeEnabled()
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:'test-results/prompts-settings-mobile.png',fullPage:true})
 }finally{
  await page.goto('/#settings/prompts').catch(()=>{})
  if(original)await fixed.fill(original).catch(()=>{})
  const save=page.getByRole('button',{name:'保存固定提示词',exact:true})
  if(await save.isEnabled())await save.click()
  await page.waitForTimeout(300)
 }
})
