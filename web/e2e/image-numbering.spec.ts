import {test,expect} from '@playwright/test'

test('图片跨页编号、重复号码续排、小写后缀与刷新后整批还原',async({page})=>{
 await page.goto('/');await page.getByLabel('用户名',{exact:true}).fill('admin');await page.getByLabel('密码',{exact:true}).fill('test-password-123');await page.getByRole('button',{name:'登录',exact:true}).click()
 await page.getByRole('button',{name:'图片编号测试',exact:true}).click()
 await expect(page.getByRole('button',{name:'一键编号',exact:true})).toHaveCount(0)
 await page.getByRole('combobox',{name:'类型筛选',exact:true}).click();await page.getByRole('option',{name:'图片',exact:true}).click()
 await expect(page.getByText('1.JPG',{exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'一键编号',exact:true})).toBeEnabled()
 await page.getByRole('button',{name:'一键编号',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'图片编号预览',exact:true})
 await expect(dialog).toContainText('共 205 张图片，205 张需要修改')
 await expect(dialog.locator('tbody tr').nth(0)).toHaveText('1.JPG1.jpg')
 await expect(dialog.locator('tbody tr').nth(1)).toHaveText('1.PNG4.png')
 await expect(dialog.locator('tbody tr').nth(2)).toHaveText('3.WEBP3.webp')
 await expect(dialog.locator('tbody tr').nth(3)).toHaveText('photo-000.PNG5.png')
 await dialog.getByRole('button',{name:'下页',exact:true}).click();await dialog.getByRole('button',{name:'下页',exact:true}).click()
 await expect(dialog.locator('tbody tr')).toHaveCount(5)
 await expect(dialog.locator('tbody tr').last()).toHaveText('photo-201.PNG206.png')
 await page.screenshot({path:'test-results/image-numbering-preview.png',fullPage:false})
 await dialog.getByRole('button',{name:'确认编号',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'图片编号记录'})).toContainText('已编号 205 张图片',{timeout:30000})
 await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).last().click()
 await expect(page.getByText('1.jpg',{exact:true})).toBeVisible();await expect(page.getByText('4.png',{exact:true})).toBeVisible()
 await page.reload()
 await page.getByRole('combobox',{name:'类型筛选',exact:true}).click();await page.getByRole('option',{name:'图片',exact:true}).click()
 await page.getByRole('button',{name:'一键编号',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText('0 张需要修改，205 张保持不变')
 await expect(page.getByRole('button',{name:'确认编号',exact:true})).toBeDisabled()
 await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
 await page.getByRole('button',{name:'编号记录',exact:true}).click()
 await page.getByRole('button',{name:'还原本次编号',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'还原图片编号',exact:true})).toContainText('205 张需要还原')
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'test-results/image-numbering-mobile.png',fullPage:false})
 await page.getByRole('button',{name:'确认整批还原',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText('已还原 205 张图片',{timeout:30000})
 await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).last().click()
 await expect(page.getByText('1.JPG',{exact:true})).toBeVisible();await expect(page.getByText('1.PNG',{exact:true})).toBeVisible()
 await page.setViewportSize({width:1440,height:1000})
 await page.getByLabel('搜索当前目录',{exact:true}).fill('photo-00')
 await expect(page.getByText('共 10 项 · 10 项 / 当前页',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'切换名称排序',exact:true}).click()
 await page.getByRole('button',{name:'一键编号',exact:true}).click()
 await expect(page.getByRole('dialog').locator('tbody tr').first()).toHaveText('photo-009.PNG4.png')
 await expect(page.getByRole('dialog').locator('tbody tr')).toHaveCount(10)
 await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
 await page.getByLabel('搜索当前目录',{exact:true}).fill('')
 await page.getByRole('combobox',{name:'类型筛选',exact:true}).click();await page.getByRole('option',{name:'视频',exact:true}).click()
 await expect(page.getByText('video.MP4',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'子目录',exact:true}).click();await page.getByRole('combobox',{name:'类型筛选',exact:true}).click();await page.getByRole('option',{name:'图片',exact:true}).click()
 await expect(page.getByText('nested.JPG',{exact:true})).toBeVisible()
})
